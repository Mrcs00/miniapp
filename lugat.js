// ── LUG'AT TOPSHIRUV LOGIKASI ──

var lugatState = {
  courseId: null,
  bolimNum: null,
  words: [],
  currentIndex: 0,
  correctCount: 0,
  wrongCount: 0,
  direction: 'kr_to_uz', // 'kr_to_uz' yoki 'uz_to_kr'
  shuffled: []
};

// Completed bo'limlarni localStorage da saqlash
function getBolimlarCompleted(courseId) {
  var key = 'completed_' + courseId;
  var data = localStorage.getItem(key);
  return data ? JSON.parse(data) : [];
}

function setBolimCompleted(courseId, bolimNum) {
  var key = 'completed_' + courseId;
  var completed = getBolimlarCompleted(courseId);
  if (completed.indexOf(bolimNum) === -1) {
    completed.push(bolimNum);
    localStorage.setItem(key, JSON.stringify(completed));
  }
}

function isBolimCompleted(courseId, bolimNum) {
  var completed = getBolimlarCompleted(courseId);
  return completed.indexOf(bolimNum) !== -1;
}

// Bo'limni ochish mumkinmi tekshirish
function isBolimUnlocked(courseId, bolimNum) {
  if (bolimNum === 1) return true; // 1-bo'lim doim ochiq
  return isBolimCompleted(courseId, bolimNum - 1);
}

// So'zlarni aralashtirish
function shuffleArray(arr) {
  var a = arr.slice();
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var tmp = a[i]; a[i] = a[j]; a[j] = tmp;
  }
  return a;
}

// Lug'at sahifasini ochish
function openLugat(courseId, bolimNum) {
  // Lug'at ma'lumotlarini olish
  var lugatData = LUGAT_1A; // Hozircha 1A uchun
  var bolimLugat = null;
  for (var i = 0; i < lugatData.length; i++) {
    if (lugatData[i].kva === bolimNum) {
      bolimLugat = lugatData[i];
      break;
    }
  }
  if (!bolimLugat) return;

  // State ni sozlash
  lugatState.courseId = courseId;
  lugatState.bolimNum = bolimNum;
  lugatState.words = bolimLugat.words;
  lugatState.currentIndex = 0;
  lugatState.correctCount = 0;
  lugatState.wrongCount = 0;
  lugatState.shuffled = shuffleArray(bolimLugat.words).slice(0, 10); // 10 ta so'z
  lugatState.direction = Math.random() > 0.5 ? 'kr_to_uz' : 'uz_to_kr';

  // Kurs rangini olish
  var course = findCourse(courseId);
  var color = course ? course.color : '#42A5F5';

  // Topbar rangini o'zgartirish
  var topbar = document.getElementById('lugat-topbar');
  if (topbar) topbar.style.background = color;

  var title = document.getElementById('lugat-title');
  if (title) title.textContent = bolimNum + "-bo'lim lug'ati";

  renderLugatSavol();
  showPage('lugat');
}

// Lug'at savolini ko'rsatish
function renderLugatSavol() {
  var word = lugatState.shuffled[lugatState.currentIndex];
  var total = lugatState.shuffled.length;
  var current = lugatState.currentIndex + 1;

  // Progress
  var progress = document.getElementById('lugat-progress-fill');
  if (progress) progress.style.width = ((current - 1) / total * 100) + '%';

  var counter = document.getElementById('lugat-counter');
  if (counter) counter.textContent = current + ' / ' + total;

  // Savol matni
  var savol = document.getElementById('lugat-savol');
  var hint = document.getElementById('lugat-hint');

  if (lugatState.direction === 'kr_to_uz') {
    if (savol) savol.textContent = word.kr;
    if (hint) hint.textContent = "O'zbekcha yozing";
  } else {
    if (savol) savol.textContent = word.uz;
    if (hint) hint.textContent = "Koreyscha yozing";
  }

  // Input tozalash
  var input = document.getElementById('lugat-input');
  if (input) {
    input.value = '';
    input.focus();
    input.style.borderColor = '#e0e0e0';
  }

  // Natija yashirish
  var natija = document.getElementById('lugat-natija');
  if (natija) natija.style.display = 'none';

  var nextBtn = document.getElementById('lugat-next-btn');
  if (nextBtn) nextBtn.style.display = 'none';

  var checkBtn = document.getElementById('lugat-check-btn');
  if (checkBtn) checkBtn.style.display = 'block';

  // Tasodifiy yo'nalish o'zgartirish (har savol uchun)
  lugatState.direction = Math.random() > 0.5 ? 'kr_to_uz' : 'uz_to_kr';
}

// Javobni tekshirish
function checkLugat() {
  var word = lugatState.shuffled[lugatState.currentIndex];
  var input = document.getElementById('lugat-input');
  var userAnswer = input ? input.value.trim().toLowerCase() : '';

  var correctAnswer = lugatState.direction === 'kr_to_uz' ? word.uz.toLowerCase() : word.kr;

  // Oldingi savolning yo'nalishi (savol ko'rsatilganda o'zgartirilgan)
  // Shuning uchun qayta hisoblash kerak
  var isKrToUz = document.getElementById('lugat-hint').textContent === "O'zbekcha yozing";
  correctAnswer = isKrToUz ? word.uz.toLowerCase() : word.kr.toLowerCase();
  userAnswer = userAnswer.toLowerCase();

  var isCorrect = userAnswer === correctAnswer;

  var natija = document.getElementById('lugat-natija');
  var course = findCourse(lugatState.courseId);
  var color = course ? course.color : '#42A5F5';

  if (natija) {
    natija.style.display = 'block';
    if (isCorrect) {
      natija.innerHTML = '<span style="color:#27AE60;font-size:16px;font-weight:700">✅ To\'g\'ri!</span>';
      lugatState.correctCount++;
    } else {
      natija.innerHTML = '<span style="color:#E74C3C;font-size:16px;font-weight:700">❌ Noto\'g\'ri!</span>' +
        '<br><span style="color:#666;font-size:14px">To\'g\'ri javob: <strong>' + (isKrToUz ? word.uz : word.kr) + '</strong></span>';
      lugatState.wrongCount++;
    }
  }

  // Input rangini o'zgartirish
  if (input) input.style.borderColor = isCorrect ? '#27AE60' : '#E74C3C';

  // Tugmalarni almashtirish
  var checkBtn = document.getElementById('lugat-check-btn');
  if (checkBtn) checkBtn.style.display = 'none';

  var nextBtn = document.getElementById('lugat-next-btn');
  if (nextBtn) {
    nextBtn.style.display = 'block';
    nextBtn.style.background = color;
    var isLast = lugatState.currentIndex >= lugatState.shuffled.length - 1;
    nextBtn.textContent = isLast ? 'Natijani ko\'rish ›' : 'Keyingisi ›';
  }
}

// Keyingi savol
function nextLugatSavol() {
  lugatState.currentIndex++;
  if (lugatState.currentIndex >= lugatState.shuffled.length) {
    showLugatNatija();
  } else {
    renderLugatSavol();
  }
}

// Natija sahifasini ko'rsatish
function showLugatNatija() {
  var total = lugatState.shuffled.length;
  var correct = lugatState.correctCount;
  var percent = Math.round(correct / total * 100);

  var course = findCourse(lugatState.courseId);
  var color = course ? course.color : '#42A5F5';

  var natijaSahifa = document.getElementById('lugat-natija-sahifa');
  var savolSahifa = document.getElementById('lugat-savol-sahifa');
  if (natijaSahifa) natijaSahifa.style.display = 'flex';
  if (savolSahifa) savolSahifa.style.display = 'none';

  var percentEl = document.getElementById('lugat-natija-percent');
  if (percentEl) percentEl.textContent = percent + '%';

  var textEl = document.getElementById('lugat-natija-text');
  var isPassed = percent >= 70;

  if (textEl) {
    if (isPassed) {
      textEl.innerHTML = '<span style="color:#27AE60;font-weight:700">✅ Tabriklaymiz!</span><br>' +
        correct + ' / ' + total + ' to\'g\'ri';
    } else {
      textEl.innerHTML = '<span style="color:#E74C3C;font-weight:700">❌ Yana urinib ko\'ring</span><br>' +
        correct + ' / ' + total + ' to\'g\'ri (70% kerak)';
    }
  }

  var retryBtn = document.getElementById('lugat-retry-btn');
  var continueBtn = document.getElementById('lugat-continue-btn');

  if (retryBtn) retryBtn.style.display = isPassed ? 'none' : 'block';
  if (continueBtn) {
    continueBtn.style.display = isPassed ? 'block' : 'none';
    continueBtn.style.background = color;
  }

  // O'tgan bo'lsa — keyingi bo'limni ochish
  if (isPassed) {
    setBolimCompleted(lugatState.courseId, lugatState.bolimNum);
  }
}

// Qayta urinish
function retryLugat() {
  lugatState.currentIndex = 0;
  lugatState.correctCount = 0;
  lugatState.wrongCount = 0;
  lugatState.shuffled = shuffleArray(lugatState.words).slice(0, 10);

  var natijaSahifa = document.getElementById('lugat-natija-sahifa');
  var savolSahifa = document.getElementById('lugat-savol-sahifa');
  if (natijaSahifa) natijaSahifa.style.display = 'none';
  if (savolSahifa) savolSahifa.style.display = 'block';

  renderLugatSavol();
}

// Davom etish — keyingi bo'lim
function continueLugat() {
  showPage('course-detail');
}

// Enter bosish
function lugatInputKeydown(e) {
  if (e.key === 'Enter') {
    var checkBtn = document.getElementById('lugat-check-btn');
    var nextBtn = document.getElementById('lugat-next-btn');
    if (checkBtn && checkBtn.style.display !== 'none') {
      checkLugat();
    } else if (nextBtn && nextBtn.style.display !== 'none') {
      nextLugatSavol();
    }
  }
}
